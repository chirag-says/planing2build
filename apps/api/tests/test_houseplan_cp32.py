WEB_FIXTURES = Path(__file__).resolve().parents[2] / "web" / "tests" / "fixtures" / "houseplans"
REVIEWED = (
    "1bhk_25x40_south_small",
    "2bhk_30x50_north_twowheeler_open",
    "2bhk_40x80_west_two_cars",
    "3bhk_45x70_two_cars_puja",
    "3bhk_50x60_wide_two_cars",
    "q06_4bhk_60x90_large_two_cars_puja_utility",
    "prop_very_wide_80x28",
    "1bhk_30x40_no_parking",
)
TYPES = (RoomType.WC, RoomType.UTILITY, RoomType.PUJA, RoomType.BEDROOM)


@cache
def plan_of(name: str) -> HousePlan:
    data = json.loads((WEB_FIXTURES / f"{name}.json").read_text("utf-8"))
    return HousePlan.model_validate(data["document"])


@cache
def intent_of_case(name: str) -> ArchitecturalIntent:
    return intent_of(benchmark_cases()[name], ruleset())


def run(name: str, op: AddRoomOutside, plan: HousePlan | None = None) -> EditResult:
    return edit(
        plan or plan_of(name),
        [op],
        ruleset(),
        intent=intent_of_case(name),
        ruleset_version=None,
        ruleset_sha256=None,
    )


def fitting_op(slot: InsertionSlot, room_type: RoomType) -> AddRoomOutside | None:
    """The smallest room of `room_type` the slot holds (clear minimums plus the walls, on the
    grid), or None when it does not fit: the check the editor makes before sending."""
    rule = ruleset().rooms[room_type]
    step = ruleset().grid_mm

    def up(v: int) -> int:
        return -(-v // step) * step

    depth = up(rule.min_short_mm + slot.depth_allowance_mm)
    clear_depth = depth - slot.depth_allowance_mm
    length = up(
        max(
            rule.min_short_mm + slot.length_allowance_mm,
            -(-rule.min_area_mm2 // clear_depth) + slot.length_allowance_mm,
        )
    )
    if depth > slot.max_depth_mm or length > slot.length_mm:
        return None
    return AddRoomOutside(
        host_room=slot.host_room,
        type=room_type,
        side=slot.side,
        offset_mm=slot.offset_mm,
        length_mm=length,
        depth_mm=depth,
    )


def accepted(name: str) -> list[tuple[AddRoomOutside, EditResult]]:
    out = []
    for slot in insertion_slots(plan_of(name), ruleset()):
        for room_type in TYPES:
            op = fitting_op(slot, room_type)
            if op is None:
                continue
            try:
                result = run(name, op)
            except BatchRejected:
                continue
            if result.report.valid:
                out.append((op, result))
    return out


def assert_canonical(plan: HousePlan) -> None:
    floor = plan.floors[0]
    rects = room_rects(floor)
    rebuilt = _rebuild(floor, rects, Change(rects=rects, rooms=list(floor.rooms)), ruleset())
    assert dump(rebuilt) == dump(floor)


# ---------- slots ----------


@pytest.mark.parametrize("name", REVIEWED)
def test_slots_are_deterministic_open_and_inside_the_buildable_area(name: str) -> None:
    plan = plan_of(name)
    slots = insertion_slots(plan, ruleset())
    assert slots == insertion_slots(plan_of(name), ruleset())
    rects = room_rects(plan.floors[0])
    o = ruleset().openings
    for slot in slots:
        assert slot.length_mm >= o.door_width_mm + 2 * o.jamb_clearance_mm
        assert slot.max_depth_mm > 0
        assert slot.open_area_kind in ("FORECOURT", "SIDE_YARD", "REAR_YARD", "COURT")
        op = AddRoomOutside(
            host_room=slot.host_room,
            type=RoomType.UTILITY,
            side=slot.side,
            offset_mm=slot.offset_mm,
            length_mm=slot.length_mm,
            depth_mm=slot.max_depth_mm,
        )
        # the whole slot at full depth never fails the placement checks (the validator may still
        # judge the room), and one millimetre deeper leaves the area or meets a room
        refusal = None
        try:
            apply(plan, op, ruleset())
        except OperationRejected as rejected:
            refusal = rejected.code
        assert refusal in (
            None,
            PlanOpRejection.HOSTED_ITEM_LEAVES_WALL,
            PlanOpRejection.HOSTED_ITEM_CHANGES_ROOMS,
        )
        deeper = op.model_copy(update={"depth_mm": slot.max_depth_mm + 1})
        with pytest.raises(OperationRejected) as caught:
            apply(plan, deeper, ruleset())
        assert caught.value.code in (
            PlanOpRejection.OUTSIDE_BUILDABLE_AREA,
            PlanOpRejection.ROOMS_WOULD_OVERLAP,
        )
        assert slot.host_room in rects


def test_a_plan_without_open_space_against_its_walls_offers_no_slot() -> None:
    assert insertion_slots(plan_of("1bhk_30x40_no_parking"), ruleset()) == []


