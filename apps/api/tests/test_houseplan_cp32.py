@pytest.mark.parametrize(
    "name",
    [
        "1bhk_25x40_south_small",
        "2bhk_30x50_north_twowheeler_open",
        "2bhk_40x80_west_two_cars",
        "3bhk_45x70_two_cars_puja",
        "3bhk_50x60_wide_two_cars",
        "q06_4bhk_60x90_large_two_cars_puja_utility",
        "prop_very_wide_80x28",
    ],
)
def test_a_room_added_in_open_space_is_valid_connected_and_recorded(name: str) -> None:
    plan = plan_of(name)
    hits = accepted(name)
    assert hits, f"no open-area room fits in {name}"
    op, result = hits[0]
    edited = result.plan
    before, after = room_rects(plan.floors[0]), room_rects(edited.floors[0])
    new = next(r for r in edited.floors[0].rooms if r.id not in before)
    # existing rooms untouched, the new one where asked, nothing overlapping
    assert {k: v for k, v in after.items() if k != new.id} == before
    keys = list(after)
    for i, a in enumerate(keys):
        for b in keys[i + 1 :]:
            assert after[a].overlap_area(after[b]) == 0
    assert new.type == op.type
    assert new.origin.kind == OriginKind.USER_EDIT
    assert_canonical(edited)
    # one door from the host; a window when the type needs one; the old openings unchanged
    links = {k: frozenset(v.connects) for k, v in analyse(edited).openings.items()}
    doors = [
        k
        for k, c in links.items()
        if c == {op.host_room, new.id}
        and next(o for o in edited.floors[0].openings if o.id == k).kind == OpeningKind.DOOR
    ]
    assert len(doors) == 1
    if ruleset().rooms[op.type].needs_window:
        assert any(
            new.id in c and "EXTERIOR" in c
            for k, c in links.items()
            if next(o for o in edited.floors[0].openings if o.id == k).kind == OpeningKind.WINDOW
        )
    old = {k: frozenset(v.connects) for k, v in analyse(plan).openings.items()}
    assert {k: links[k] for k in old} == old
    (record,) = edited.compromises
    assert record.change_key == ProgrammeChange.ROOM_ADDED_BY_OWNER
    assert record.params == {"room": new.id, "room_type": op.type.value}
    assert result.inverse == (RevertToRevision(revision=plan.meta.revision_no),)
    # deterministic, and the open areas recalculated: less open area by the room's footprint
    again, _ = apply_edit(plan, [op], ruleset())
    assert sha256_of(again.body()) == sha256_of(edited.body())
    open_before = sum(a.area_mm2 for a in plan_geometry(plan, ruleset()).floors[0].open_areas)
    open_after = sum(a.area_mm2 for a in plan_geometry(edited, ruleset()).floors[0].open_areas)
    assert open_before - open_after == after[new.id].area


def test_most_plans_with_open_space_take_several_kinds_of_room() -> None:
    counts = {name: len(accepted(name)) for name in REVIEWED}
    assert sum(1 for n in counts.values() if n > 0) >= 7
    assert sum(counts.values()) >= 20


