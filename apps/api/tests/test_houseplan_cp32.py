def test_impossible_insertions_are_refused_with_a_reason() -> None:
    name = "3bhk_50x60_wide_two_cars"
    plan = plan_of(name)
    rules = ruleset()
    slot = insertion_slots(plan, rules)[0]
    rects = room_rects(plan.floors[0])
    base = AddRoomOutside(
        host_room=slot.host_room,
        type=RoomType.UTILITY,
        side=slot.side,
        offset_mm=slot.offset_mm,
        length_mm=slot.length_mm,
        depth_mm=min(slot.max_depth_mm, 1500),
    )
    # a side another room meets
    inner = next(
        (k, side, touching(rects, k, side)[0])
        for k in rects
        for side in RoomSide
        if k != "parking" and touching(rects, k, side)
    )
    _, lo, _ = side_line(rects[inner[0]], inner[1])
    cases: list[tuple[AddRoomOutside, PlanOpRejection]] = [
        (base.model_copy(update={"type": RoomType.PARKING}), PlanOpRejection.ROOM_TYPE_NOT_ALLOWED),
        (base.model_copy(update={"type": RoomType.STORE}), PlanOpRejection.ROOM_TYPE_NOT_ALLOWED),
        (
            base.model_copy(update={"offset_mm": slot.offset_mm + 1_000_000 - slot.length_mm}),
            PlanOpRejection.NOT_ON_OUTSIDE_WALL,
        ),
        (
            base.model_copy(
                update={
                    "host_room": inner[0],
                    "side": inner[1],
                    "offset_mm": inner[2][0] - lo,
                    "length_mm": inner[2][1] - inner[2][0],
                }
            ),
            PlanOpRejection.NOT_ON_OUTSIDE_WALL,
        ),
        (base.model_copy(update={"depth_mm": 900_000}), PlanOpRejection.OUTSIDE_BUILDABLE_AREA),
        (base.model_copy(update={"host_room": "parking"}), PlanOpRejection.NOT_ON_OUTSIDE_WALL),
    ]
    for op, code in cases:
        with pytest.raises(OperationRejected) as caught:
            apply(plan, op, rules)
        assert caught.value.code == code, op
    with pytest.raises(OperationRejected) as needs_rules:
        apply(plan, base)
    assert needs_rules.value.code == PlanOpRejection.NOT_SUPPORTED


def test_a_room_too_small_for_its_type_is_judged_by_the_validator_and_not_stored() -> None:
    name = "3bhk_50x60_wide_two_cars"
    slot = insertion_slots(plan_of(name), ruleset())[0]
    op = AddRoomOutside(
        host_room=slot.host_room,
        type=RoomType.BEDROOM,
        side=slot.side,
        offset_mm=slot.offset_mm,
        length_mm=ruleset().openings.door_width_mm + 2 * ruleset().openings.jamb_clearance_mm,
        depth_mm=min(slot.max_depth_mm, 1200),
    )
    result = run(name, op)
    assert not result.report.valid
    assert {e.code.value for e in result.report.errors} & {
        "ROOM_BELOW_MIN_AREA",
        "ROOM_BELOW_MIN_SHORT_SIDE",
    }


def test_a_door_needs_room_on_the_shared_wall() -> None:
    name = "3bhk_50x60_wide_two_cars"
    slot = insertion_slots(plan_of(name), ruleset())[0]
    op = AddRoomOutside(
        host_room=slot.host_room,
        type=RoomType.UTILITY,
        side=slot.side,
        offset_mm=slot.offset_mm,
        length_mm=ruleset().openings.door_width_mm,
        depth_mm=min(slot.max_depth_mm, 1500),
    )
    with pytest.raises(OperationRejected) as caught:
        apply(plan_of(name), op, ruleset())
    assert caught.value.code == PlanOpRejection.DOOR_DOES_NOT_FIT
